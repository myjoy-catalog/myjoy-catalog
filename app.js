// Hero video autoplay with mobile/WeChat fallbacks
(function(){
  const hero=document.querySelector('.hero');
  const video=document.getElementById('heroVideo');
  if(!video||!hero) return;
  let started=false;
  function markFailed(){hero.classList.add('video-failed');}
  function tryPlay(){
    const pr=video.play();
    if(pr&&typeof pr.then==='function'){
      pr.then(()=>{started=true;hero.classList.remove('video-failed');})
       .catch(()=>{if(!started) markFailed();});
    }
  }
  video.addEventListener('playing',()=>{started=true;hero.classList.remove('video-failed');});
  video.addEventListener('error',markFailed);
  video.addEventListener('stalled',()=>{if(!started) markFailed();});
  // 主动唤起
  tryPlay();
  window.addEventListener('load',tryPlay);
  document.addEventListener('DOMContentLoaded',tryPlay);
  // 微信内置浏览器需等 JSBridge 就绪
  if(window.WeixinJSBridge){
    WeixinJSBridge.invoke('getNetworkType',{},tryPlay);
  }else{
    document.addEventListener('WeixinJSBridgeReady',()=>{
      WeixinJSBridge.invoke('getNetworkType',{},tryPlay);
    },false);
  }
  // 用户首次触碰时再尝试一次
  ['touchstart','click'].forEach(ev=>
    document.addEventListener(ev,function once(){tryPlay();document.removeEventListener(ev,once);},{passive:true})
  );
})();

