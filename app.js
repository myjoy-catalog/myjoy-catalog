function fcUpdateCarousel(){
  const track=document.getElementById('featuredTrack');
  const cards=track.querySelectorAll('.featured-card');
  if(!cards.length)return;
  const cardW=cards[0].getBoundingClientRect().width||1;
  const gap=parseFloat(getComputedStyle(track).gap)||16;
  const step=cardW+gap;
  const perView=Math.max(1,Math.round((track.clientWidth+gap)/step));
  const pages=Math.max(1,Math.ceil(cards.length/perView));
  const idx=Math.min(pages-1,Math.max(0,Math.round(track.scrollLeft/(step*perView))));
  // 箭头状态
  document.getElementById('fcPrev').disabled=track.scrollLeft<=2;
  document.getElementById('fcNext').disabled=track.scrollLeft+track.clientWidth>=track.scrollWidth-2;
  // 圆点（数量变化时重建）
  const dots=document.getElementById('fcDots');
  if(!fcDotsBuilt||dots.children.length!==pages){
    dots.innerHTML=Array.from({length:pages},(_,i)=>
      `<button class="fc-dot" data-page="${i}" aria-label="第 ${i+1} 组"></button>`).join('');
    dots.querySelectorAll('.fc-dot').forEach(d=>d.onclick=()=>{
      const t=document.getElementById('featuredTrack');
      const c=t.querySelector('.featured-card');
      const g=parseFloat(getComputedStyle(t).gap)||16;
      const s=(c?c.getBoundingClientRect().width:1)+g;
      const pv=Math.max(1,Math.round((t.clientWidth+g)/s));
      t.scrollTo({left:Number(d.dataset.page)*s*pv,behavior:'smooth'});
    });
    fcDotsBuilt=true;
  }
  dots.querySelectorAll('.fc-dot').forEach((d,i)=>d.classList.toggle('active',i===idx));
}
